-- Reservations of a room for a half-open time interval [start_time, end_time).
-- Cancellation is a soft deleted (status = 'CANCELLED'), so history is kept
-- and the slot becomes available again.
CREATE TABLE reservations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id      BIGINT                   NOT NULL,
    responsible  VARCHAR(100)             NOT NULL,
    start_time   TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time     TIMESTAMP WITH TIME ZONE NOT NULL,
    status       VARCHAR(20)              NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_reservations_room FOREIGN KEY (room_id) REFERENCES rooms (id),
    CONSTRAINT chk_reservations_time_range CHECK (end_time > start_time),
    CONSTRAINT chk_reservations_status CHECK (status IN ('ACTIVE', 'CANCELLED'))
);

-- Supports the overlap check (room + time range) and the room/date listing filter.
CREATE INDEX idx_reservations_room_start ON reservations (room_id, start_time);
-- Supports the date filter when no room is given.
CREATE INDEX idx_reservations_start ON reservations (start_time);
